/**
 * Generates a clean, formatted Markdown document for testing or printing
 */
export function exportQuizToMarkdown(quiz: QuizData, includeAnswers = true): string {
  const lines: string[] = [];
  lines.push(`# Exam / Quiz: ${quiz.topic}`);
  lines.push(`*Total Questions: ${quiz.questions.length} | Date Generated: ${new Date().toLocaleDateString()}*\n`);
  lines.push('---\n');

  quiz.questions.forEach((q, idx) => {
    lines.push(`### Question ${idx + 1}`);
    lines.push(`${q.question}\n`);
    q.options.forEach((opt, oIdx) => {
      lines.push(`- **${String.fromCharCode(65 + oIdx)}.** ${opt}`);
    });
    lines.push('');
  });

  if (includeAnswers) {
    lines.push('\n---\n');
    lines.push('## 📝 Answer Key & Explanations\n');
    quiz.questions.forEach((q, idx) => {
      const correctLetter = String.fromCharCode(65 + q.correctAnswer);
      lines.push(`**Q${idx + 1}:** ${correctLetter} - *${q.options[q.correctAnswer]}*`);
      lines.push(`> **Explanation:** ${q.explanation}\n`);
    });
  }

  return lines.join('\n');
}

